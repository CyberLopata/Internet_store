# довші назви перевіряємо першими: «темно-синій» має виграти у «синій»
_ORDERED = sorted(COLORS, key=len, reverse=True)


def hex_for_name(name):
    """Код кольору за назвою або "", якщо назву не впізнано."""
    n = (name or "").strip().lower().replace("ʼ", "'")
    if not n:
        return ""
    if n in COLORS:
        return COLORS[n]
    for key in _ORDERED:
        if key in n:
            return COLORS[key]
    return ""
